-- DS-P2.326: the PolarFire SoC platform fabric. This file holds the body that
-- deepskopion_pfsoc_top.vhd carried until DS-P2.326, moved verbatim; the product
-- top is now a thin wrapper that passes every port straight through to this
-- entity and leaves fic0_rd_probe_o open. A bench top (bench/, DS-P2.326) wraps
-- the same fabric with an on-chip analyzer on that probe. The design notes for
-- this platform shell follow, unchanged.
--
-- PF-H0 (DS-P2.124) — PolarFire SoC / MPFS-DISCO-KIT platform shell. The THIRD
-- wrapper around the vendor-neutral deepskopion_core (after the Zynq
-- deepskopion_top and the Agilex DE25 top). Per PF-P0 (docs/design/
-- pfsoc_port_plan.md):
--
--   * The MSS subsystem (DDR4 / SD / MMUART / MAC-SGMII / FIC ports) is a hard
--     block generated by the Libero PolarFire SoC MSS Configurator from the
--     frozen `hardware.mss` .cxz, wired to the fabric by the Libero SmartDesign
--     builder tcl (hw/libero/pfsoc/pfsoc_mss_subsys.tcl, tcl_hooks.gen_project).
--     This VHDL declares the `pfsoc_mss` component whose fabric interface that
--     SmartDesign presents — the structural analog of the DE25 `hps_subsys`.
--     Every port of this component maps 1:1 to a real MSS component pin in the
--     builder tcl (guarded by test_pfsoc_mss_builder_contract.py, which asserts
--     the tcl's created SmartDesign ports equal this component's ports).
--   * deepskopion_core is instantiated UNCHANGED except for its generics: the
--     PolarFire MSS-FIC backend (G_DDR_BACKEND => "fic"), 64-bit / 64-beat FIC
--     widths (G_DDR_DATA_WIDTH => 64, G_AXI_MAX_BURST => 64), the 256 MiB ring at
--     0xA0000000, and clk_sys kept at 100 MHz so the ZS/CAN/telemetry arithmetic
--     is bit-identical to the other two legs.
--   * The CSR plane reuses hw/rtl/de25/{axil_demux3,axil_apb_shim,
--     lwh2f_axilite_bridge}.vhd VERBATIM (they are vendor-neutral fabric RTL).
--     FIC0 is a full AXI4 initiator (IDs, AWLEN/AWSIZE/AWBURST, WLAST — PF-P0
--     §3.2 "MSS FIC (AXI4) → fabric AXI-Lite demux"); the DE25-proven
--     `lwh2f_axilite_bridge` thins it to single-beat AXI-Lite (echoing IDs,
--     tying RLAST) before the demux, exactly as the DE25 leg thins the Agilex
--     lwh2f full-AXI4 master. This is PF-P0 §1.3's "FIC sibling" option, taken
--     by reusing the vendor-neutral bridge verbatim rather than the electrically
--     false "demux takes the FIC AXI directly" alternative.
--   * The ring write path is the core's AXI4 master records driven straight onto
--     the FIC1 AXI4 target (64-bit), the DE25 f2sdram role played by the MSS FIC.
--   * Interrupts {CTU B, CTU A, ring watermark} drive the low three lines of the
--     MSS 64-bit F2M fabric-interrupt group (MSS_INT_F2M[2:0]); the remaining
--     F2M lines are tied inactive. The F2M-bit -> PLIC source numbers are read
--     from the generated MSS handoff at bring-up (PF-P0 §3.5), not assumed here.
--
-- What this file does NOT own: the frozen MSS .cxz itself. Per PF-P0 §3.1 that
-- harvest-and-freeze is THIS ticket's (PF-H0) obligation, but it requires the
-- Microchip Discovery Kit reference-design bundle and a bench MSS Configurator
-- run and could not be reproduced from a boardless clone — see
-- hw/libero/pfsoc/mss/README.md for the honest blocker and the failing
-- completeness gate (test_pfsoc_target_contract.py::test_pfsoc_frozen_mss_is_vendored).
-- Also deferred: the generated FIC fabric base address and PLIC source numbers
-- (read from the MSS handoff, PF-L0), and the Microchip identity transport
-- (RTL-I2). Those are marked at their seams below.
