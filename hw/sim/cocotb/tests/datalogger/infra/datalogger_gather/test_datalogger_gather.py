@cocotb.test()
@requires("SGA-REQ-7")
async def test_counters_zero_at_idle_and_under_traffic(dut):
    """SGA-REQ-7: `PROTO_PKT_CNT_FLAT` and `PROTO_ERR_CNT_FLAT` track
    per-protocol handshakes + errors. Two phases:

    Phase A (idle): with no protocol traffic, every slot stays at 0
    indefinitely. Catches reset-then-leak bugs (counter not properly
    reset, or datalogger emitting handshakes on idle pin levels).

    Phase B (traffic): drive K=8 EDGE events on EDGE0 only. Assert
    `PROTO_PKT_CNT_FLAT[EDGE]` == K AND every OTHER protocol slot stays
    at 0 (no cross-protocol leak of the counter increment).

    Error counters stay at 0 across both phases (no driven errors).

    DS-T2.55: the EDGE slot index is `EDGE_PROTO_IDX` derived from
    datalogger_config.yml (currently 1, not 0) — the previous hardcoded idx-0
    read the CAN slot and was the parked false "EDGE pkt_cnt stays 0".
    """
    env = TbEnv(dut, clk="CLK", rst="RST", period_ns=PERIOD_NS)
    await env.start_clock()
    await reset_dut(dut)
    dut.DOUT_REQ.value = 1

    # ── Phase A: idle ──
    await ClockCycles(dut.CLK, 200)

    for idx in range(N_PROTO):
        pkt = get_proto_pkt_cnt(dut, idx)
        err = get_proto_err_cnt(dut, idx)
        assert pkt == 0 and err == 0, (
            f"SGA-REQ-7 phase-A: PROTO_COUNTERS[{idx}] non-zero at idle. "
            f"pkt_cnt={pkt}, err_cnt={err}. File T-tier."
        )

    # ── Phase B: drive K EDGE0 events, assert per-protocol counts ──
    EDGE0_DEV_ID = 1
    EDGE0_PIN = 42
    EDGE_ENABLE_CODE = 0b01
    K = 8

    pins_idle_no_edge0 = IDLE_CAPTURE_PINS & ~(1 << EDGE0_PIN)
    dut.CAPTURE_PINS.value = pins_idle_no_edge0
    dut.CONFIG.value = 0
    await ClockCycles(dut.CLK, 4)
    dut.CONFIG.value = (EDGE0_DEV_ID << 11) | EDGE_ENABLE_CODE
    await ClockCycles(dut.CLK, 16)
    # DS-T2.43: the ENABLED lifecycle frame is itself one EDGE handshake — it
    # bumps pkt_cnt by 1. Snapshot the post-enable baseline so we assert the
    # DELTA from the K driven edges, not an absolute that now folds in the
    # marker.
    edge_idx = EDGE_PROTO_IDX    # DS-T2.55: datalogger_config-derived EDGE slot
    edge_pkt_base = get_proto_pkt_cnt(dut, edge_idx)

    pin_state = 0
    levels = pins_idle_no_edge0
    EDGE0_BIT = 1 << EDGE0_PIN
    for _ in range(K):
        pin_state ^= 1
        if pin_state:
            levels |= EDGE0_BIT
        else:
            levels &= ~EDGE0_BIT
        dut.CAPTURE_PINS.value = levels
        await ClockCycles(dut.CLK, 4)
    await ClockCycles(dut.CLK, 128)

    edge_pkt = get_proto_pkt_cnt(dut, edge_idx) - edge_pkt_base
    assert edge_pkt == K, (
        f"SGA-REQ-7 phase-B: PROTO_PKT_CNT_FLAT[EDGE] delta={edge_pkt}, "
        f"expected {K} (baseline {edge_pkt_base} excludes the ENABLED "
        f"lifecycle marker). EDGE handshake counter is dropping events or "
        f"the increment path is broken. File T-tier."
    )
    for idx in range(N_PROTO):   # every NON-EDGE protocol slot
        if idx == edge_idx:
            continue
        pkt = get_proto_pkt_cnt(dut, idx)
        assert pkt == 0, (
            f"SGA-REQ-7 phase-B cross-talk: PROTO_PKT_CNT_FLAT[{idx}]"
            f"={pkt}, expected 0 — only EDGE (idx {edge_idx}) was driven. "
            f"Counter aggregation is leaking across protocols. File T-tier."
        )

    for idx in range(N_PROTO):
        err = get_proto_err_cnt(dut, idx)
        assert err == 0, (
            f"SGA-REQ-7 phase-B: PROTO_ERR_CNT_FLAT[{idx}]={err}, "
            f"expected 0 — no errors were driven. File T-tier."
        )

    dut._log.info(
        f"SGA-REQ-7: PROTO_PKT_CNT_FLAT[EDGE]={edge_pkt} (driven K={K}); "
        f"all other proto slots + err slots stayed at 0."
    )


