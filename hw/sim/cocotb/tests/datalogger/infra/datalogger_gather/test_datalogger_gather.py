def _proto_index_map():
    """DS-T2.55: derive the per-protocol PROTO_COUNTERS index map straight from
    datalogger_config.yml — DO NOT hardcode it. The gather's C_PROTO_IDX_* / the
    tb_datalogger_gather flatten order are generated by datalogger_gather_gen.py as the
    ALPHABETICAL position of each enabled protocol prefix among the union of
    burst + stream protocols (``sorted(all_protocols.keys())``). When CAN + JTAG
    were activated (DS-P3.100 / DS-P3.56) that pushed EDGE from index 0 to index
    1 and grew C_NUM_PROTO_COUNTERS 4→6, but this test still read idx 0 for EDGE
    — i.e. it was silently sampling the CAN slot (never driven → always 0), the
    root cause of DS-T2.55. Mirroring the generator here makes the map
    drift-proof: a newly enabled protocol re-indexes automatically.

    Returns (index_by_prefix, n_proto). Prefixes are upper-cased, matching the
    VHDL C_PROTO_IDX_<PREFIX> constants (EDGE, I2C, SPI, UART, JTAG, CAN, ...).
    """
    import yaml

    cfg_path = (
        DEEPSKOPION_ROOT / "tools" / "datalogger-builder" / "config" / "datalogger_config.yml"
    )
    with open(cfg_path, "r", encoding="utf-8", errors="replace") as fh:
        cfg = yaml.safe_load(fh)

    prefixes = set()
    for tier in ("Burst", "Stream"):
        for proto_name in (cfg.get("Dataloggers", {}).get(tier, {}) or {}):
            prefixes.add(proto_name.upper())   # 'Edge' → 'EDGE', 'I2c' → 'I2C'
    ordered = sorted(prefixes)
    return {p: i for i, p in enumerate(ordered)}, len(ordered)


PROTO_IDX, N_PROTO = _proto_index_map()
EDGE_PROTO_IDX = PROTO_IDX["EDGE"]   # DS-T2.55: the real EDGE slot (1, not 0)

# Bus-idle pin levels per protocol (high-Z buses pulled high for
# I2C/UART/SPI; edge pins at low when nothing is happening).
IDLE_CAPTURE_PINS = (
    (1 << 12) | (1 << 13) | (1 << 14) | (1 << 15) |   # I2C SCL/SDA pairs
    (1 << 20) | (1 << 21) | (1 << 22) | (1 << 23) |   # SPI CS/MOSI/MISO/SCLK
    (1 << 36) | (1 << 37)                              # UART TX pins
    # EDGE slots (42-44) stay at 0 when idle.
)


# ── Helpers ─────────────────────────────────────────────────────────────────

def get_proto_pkt_cnt(dut, idx):
    """Read pkt_cnt for protocol index `idx` from the flattened bus."""
    flat = int(dut.PROTO_PKT_CNT_FLAT.value)
    return (flat >> (idx * 32)) & 0xFFFFFFFF


def get_proto_err_cnt(dut, idx):
    flat = int(dut.PROTO_ERR_CNT_FLAT.value)
    return (flat >> (idx * 32)) & 0xFFFFFFFF


def get_proto_drop_cnt(dut, idx):
    """Read drop_cnt (DS-T2.22 backpressure: req && !ack) for protocol idx."""
    flat = int(dut.PROTO_DROP_CNT_FLAT.value)
    return (flat >> (idx * 32)) & 0xFFFFFFFF


async def reset_dut(dut, n_cycles=8, settle_cycles=32):
    """Active-high reset + settle window (same hygiene as arbiter / framer)."""
    dut.RST.value = 1
    dut.DOUT_REQ.value = 0
    dut.CAPTURE_PINS.value = IDLE_CAPTURE_PINS
    dut.CONFIG.value = 0
    dut.TIMESTAMP.value = 0
    await ClockCycles(dut.CLK, n_cycles)
    dut.RST.value = 0
    await ClockCycles(dut.CLK, settle_cycles)


def is_edge_lifecycle(payload):
    """DS-T2.43: EDGE lifecycle (ENABLED/DISABLED) frames carry type bits
    [26:24]==0b100 (C_ED_TYPE_EVENT); a normal edge event has [26:24]={s,f,e}
    with s=0 under capturing-enable (codes 0b000/0b001). Used to exclude
    out-of-band lifecycle markers from edge DATA-event counts."""
    return ((payload >> 24) & 0x7) == 0b100


async def drain_lifecycle(dut, max_cycles=512):
    """Flush enable/disable lifecycle frames (DS-T2.43: every datalogger, edge
    included, now emits an in-band ENABLED frame on the CONFIG enable edge and a
    DISABLED frame on the disable edge) to burst-FIFO-empty, so a subsequent
    EXACT edge-count measurement isn't off-by-one. Requires the caller to want
    DOUT_REQ asserted; restores nothing. Returns frames drained."""
    dut.DOUT_REQ.value = 1
    drained = quiet = 0
    for _ in range(max_cycles):
        await RisingEdge(dut.CLK)
        try:
            if int(dut.DOUT_VALID.value) == 1:
                drained += 1
        except ValueError:
            pass
        if int(dut.FIFO_BURST_EMPTY.value) == 1:
            quiet += 1
            if quiet >= 32:
                break
        else:
            quiet = 0
    return drained


