"""DS-T2.86 — the DE25 contract's map-access preamble walks the regbank, not low HPS memory.

WHAT THIS GUARDS
----------------
routertl's map-access preamble (RTL-P2.1213) walks the register map
``runtimes/hw.yml`` names before every REQ. It used to name
``project_regbank.yml``, which declares no base and no address mode, so the
preamble resolved GIT_HASH at 0x00000000 and HEARTBEAT_CNT at 0x00000300:
low HPS physical addresses on the devmem probe, not the lwh2f regbank at
0x20000000. The contract now names ``runtimes/de25_regbank_map.yml``,
generated by ``tools/de25_regbank_map.py``. One part each:

* contract-map: the map routertl resolves from the committed contract puts
  each register at 0x20000000 + its byte offset, inside the CSR aperture;
* map-fresh: ``tools/de25_regbank_map.py --check`` refuses a view that no
  longer matches project_regbank.yml or the target's CSR aperture, so the
  copy cannot drift silently. The committed view is checked fresh.

POWER
-----
* BASELINE (origin/main before DS-T2.86): the contract names
  project_regbank.yml and the generator does not exist, so both parts are RED
  on their ``DS-T2.86[<part>]`` assertion.
* MUTATIONS: one per part, recorded in the test-power receipt.

DEPLOYMENT ENVIRONMENT
----------------------
No hardware, no network. Imports routertl's contract loader and map
preamble from the installed ``rr``; runs the generator CLI with this
interpreter. Writes only under pytest's ``tmp_path``.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "runtimes" / "hw.yml"
GEN = ROOT / "tools" / "de25_regbank_map.py"
VIEW = Path("runtimes") / "de25_regbank_map.yml"
INPUTS = ("project_regbank.yml", "targets/de25_datalogger.yml",
          "tools/de25_regbank_map.py", "tools/hw_run_hps_devmem.py")


def _contract_map() -> dict[str, str]:
    """``{register: address}`` the way rr hw run resolves the preamble map."""
    from sdk.engine.hardware.contract import load_contract
    from sdk.engine.hardware.map_preamble import load_declared_map, resolve_regbank_path
    from sdk.engine.hardware.sta_coverage import project_root_for_contract

    contract = load_contract(CONTRACT)
    path = resolve_regbank_path(project_root_for_contract(CONTRACT), contract)
    assert path is not None, "DS-T2.86[contract-map]: contract resolves no register map"
    return {r["name"]: r["address"] for r in load_declared_map(path, contract=contract)}


def _gen(project: Path, *args: str) -> subprocess.CompletedProcess:
    assert GEN.is_file(), \
        f"DS-T2.86[map-fresh]: no generator for the contract's map ({GEN.relative_to(ROOT)})"
    return subprocess.run([sys.executable, str(project / "tools" / "de25_regbank_map.py"),
                           "--project", str(project), *args],
                          capture_output=True, text=True, timeout=120)


def _check(project: Path) -> subprocess.CompletedProcess:
    return _gen(project, "--check")


# ── contract-map ──────────────────────────────────────────────────────────


def test_contract_preamble_map_is_the_byte_addressed_regbank():
    tag = "DS-T2.86[contract-map]"
    amap = _contract_map()
    got = {n: int(amap[n], 16) for n in
           ("GIT_HASH", "DATALOGGER_CONFIG", "HEARTBEAT_CNT", "RING_WRITE_PTR",
            "EYE_PHASE_STATUS")}
    assert got == {"GIT_HASH": 0x20000000, "DATALOGGER_CONFIG": 0x20000020,
                   "HEARTBEAT_CNT": 0x200000C0, "RING_WRITE_PTR": 0x20000150,
                   "EYE_PHASE_STATUS": 0x2000021C}, \
        f"{tag}: preamble map is not the regbank at 0x20000000 in byte mode: " \
        + ", ".join(f"{n}=0x{a:08X}" for n, a in got.items())
    outside = {n: a for n, a in amap.items()
               if not 0x20000000 <= int(a, 16) < 0x20001000}
    assert len(amap) == 75 and not outside, \
        f"{tag}: {len(amap)} registers, outside the CSR aperture: {outside}"


# ── map-fresh ─────────────────────────────────────────────────────────────


def _project(tmp_path: Path) -> Path:
    """The generator's sources copied into tmp_path, with a view generated from them."""
    proj = tmp_path / "deepskopion"
    for rel in INPUTS:
        (proj / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, proj / rel)
    res = _gen(proj)
    assert res.returncode == 0, f"DS-T2.86[map-fresh]: generation failed:\n{res.stderr}"
    return proj


def test_committed_view_is_fresh():
    res = _check(ROOT)
    assert res.returncode == 0, \
        f"DS-T2.86[map-fresh]: committed {VIEW} is stale:\n{res.stdout}{res.stderr}"


def test_check_refuses_a_view_that_drifted_from_its_sources(tmp_path):
    tag = "DS-T2.86[map-fresh]"
    proj = _project(tmp_path)
    res = _check(proj)
    assert res.returncode == 0, f"{tag}: unmodified copy reported stale:\n{res.stderr}"

    regbank = proj / "project_regbank.yml"
    doc = yaml.safe_load(regbank.read_text(encoding="utf-8"))
    doc["registers"].append({"name": "NEW_REG", "address": 0x0248, "access": "RO"})
    regbank.write_text(yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    res = _check(proj)
    assert res.returncode == 1 and "STALE" in res.stderr, \
        f"{tag}: a register added to project_regbank.yml passed --check: " \
        f"rc={res.returncode}\n{res.stdout}{res.stderr}"

    proj = _project(tmp_path / "rebased")
    target = proj / "targets" / "de25_datalogger.yml"
    target.write_text(target.read_text(encoding="utf-8").replace(
        "reg: [0x20000000, 0x1000]", "reg: [0x30000000, 0x1000]"), encoding="utf-8")
    res = _check(proj)
    assert res.returncode == 1 and "STALE" in res.stderr, \
        f"{tag}: a moved CSR aperture passed --check: rc={res.returncode}\n{res.stderr}"
