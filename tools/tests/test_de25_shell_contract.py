def test_target_local_generation_and_regenerated_ip():
    """DS-P1.52, DS-P2.196: the HPS subsystem is declared in the project-root
    ip.yml and generated by rr's own pre-synth HPS generator, not by the retired
    hw/quartus/de25/de25_hps_subsys.tcl qsys-script (that hand-tcl
    add_component hook LOOKED like the proven fix and passed its own static
    text guard, but a fresh queued bitstream still failed quartus_pfg Error
    20809 — no real HPS partition in the .sof). The hook must stay retired:
    its reappearance would silently reintroduce a second, competing
    HPS-generation path.

    Since DS-P2.196 rr makes the HPS and EMIF variants from the declared
    parameters (``hps_regenerate``, RTL-P2.2101) and the fabric IOPLL from
    ``vendor_ip_variants``. The declaration is the board fact now, so its
    digest is pinned: change it deliberately, with the digest, never as a
    side effect.
    """
    assert not (ROOT / "hw/quartus/de25/de25_hps_subsys.tcl").exists(), (
        "hw/quartus/de25/de25_hps_subsys.tcl must stay retired (DS-P1.52) — "
        "its add_component-by-file qsys-script LOOKED like the proven "
        "RTL-P3.722 fix but measurably still produced a .sof with no real "
        "HPS partition (quartus_pfg Error 20809)."
    )
    ip_yml = yaml.safe_load((ROOT / "ip.yml").read_text())
    hps_ip = next(ip for ip in ip_yml["ips"] if ip["name"] == "hps")
    assert hps_ip["type"] == "intel_agilex_5_soc"
    assert hps_ip["config"]["hps_regenerate"] is True, (
        "ip.yml ips[].config.hps_regenerate must be true — the source tree "
        "holds no HPS .ip, and unset, rr falls back to add_instance-by-catalog-"
        "type, which silently black-boxes the HPS as an empty Generic Component."
    )
    assert "hps_frozen" not in hps_ip["config"]
    assert hps_ip["config"]["hps_emif"] is True, (
        "hps_emif must stay true — without the io96b EMIF the HPS has no "
        "DRAM controller and the SPL never relocates (dead-silent boot)."
    )
    declaration = json.dumps(
        {"hps": hps_ip["config"], "vendor_ip_variants": ip_yml["vendor_ip_variants"]},
        sort_keys=True, separators=(",", ":"),
    ).encode()
    assert hashlib.sha256(declaration).hexdigest() == (
        "ccbd0584fdad022a2cf9c374acd3f69f8f9f037008d547658c81b2e9a90e8b6e"
    )


