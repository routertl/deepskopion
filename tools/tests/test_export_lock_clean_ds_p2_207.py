def _declared_top(target: str) -> str | None:
    """project.top_module of the target's file (targets/ or bench/targets/), following `extends`: a target name,
    or (DS-P1.103, a bench target extending a product) a .yml path relative to the extending file."""
    path: Path | None = target_file(target, ROOT)
    seen: set[Path] = set()
    while path is not None and path not in seen:
        seen.add(path)
        cfg = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        top = (cfg.get("project") or {}).get("top_module")
        if top:
            return top
        ext = cfg.get("extends")
        path = None if not ext else ((path.parent / str(ext)).resolve() if str(ext).endswith(".yml")
                                     else target_file(str(ext), ROOT))
    return None


