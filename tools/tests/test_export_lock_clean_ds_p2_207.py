def _staged_tree(root: Path, scratch: Path) -> str:
    """The tree of what is staged in *root*, written from a private copy of its index (DS-P3.262).

    `git write-tree` on the checkout's own index takes that index's lock; a git command of another test or tool
    running in the same worktree at that moment makes it fail ("Unable to create .../index.lock: File exists", the
    ds-python-suite red of 2026-11-14 at -n 8). Git replaces the index by rename, so the copy is always whole."""
    index = Path(subprocess.run(["git", "rev-parse", "--git-path", "index"], cwd=root, capture_output=True,
                                text=True, check=True).stdout.strip())
    private = scratch / "index"
    shutil.copyfile(index if index.is_absolute() else root / index, private)
    return subprocess.run(["git", "write-tree"], cwd=root, capture_output=True, text=True, check=True,
                          env=dict(os.environ, GIT_INDEX_FILE=str(private))).stdout.strip()


