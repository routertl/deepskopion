"""DS-P1.113: the HSS IOMUX overlay reads the MSS component RouteRTL generated, never a tracked path.

RouteRTL generates the PolarFire MSS component (.cxz) from the tracked disco_mss.cfg at Libero-flow time and writes
rr_mss_stamp.json beside it: "cxz" is the generated component, "cfg_sha256" the configuration it came from.
disco_iomux_config reads the component the stamp names, and refuses when the stamp is missing, unreadable, describes
another configuration, or names a component that does not exist.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import zipfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
CFG = ROOT / "hw" / "libero" / "pfsoc" / "mss" / "disco_mss.cfg"
XML_MEMBER = "disco_mss_mss_cfg.xml"


def _mod():
    spec = importlib.util.spec_from_file_location(
        "ds_p1_113_iomux", ROOT / "sw" / "linux" / "pfsoc" / "hss" / "disco_iomux_config.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _cxz(tmp_path: Path, xml: bytes = b"<generated/>") -> Path:
    cxz = tmp_path / "gen" / "disco_mss.cxz"
    cxz.parent.mkdir(parents=True)
    with zipfile.ZipFile(cxz, "w") as z:
        z.writestr(XML_MEMBER, xml)
    return cxz


def _stamp(tmp_path: Path, **fields) -> Path:
    body = {"cxz": str(_cxz(tmp_path)), "cfg": str(CFG), "cfg_sha256": hashlib.sha256(CFG.read_bytes()).hexdigest()}
    body.update(fields)
    stamp = tmp_path / "rr_mss_stamp.json"
    stamp.write_text(json.dumps(body))
    return stamp


def test_the_xml_comes_from_the_component_the_stamp_names(tmp_path):
    assert _mod().authoritative_xml_bytes(ROOT, _stamp(tmp_path)) == b"<generated/>"


def test_the_default_stamp_is_the_pfsoc_target_build_output(tmp_path):
    mod = _mod()
    (tmp_path / "hw/libero/pfsoc/mss").mkdir(parents=True)
    (tmp_path / "hw/libero/pfsoc/mss/disco_mss.cfg").write_bytes(CFG.read_bytes())
    default = tmp_path / "build" / "pfsoc_datalogger" / "mss" / "rr_mss_stamp.json"
    default.parent.mkdir(parents=True)
    default.write_text(_stamp(tmp_path).read_text())
    assert mod.authoritative_xml_bytes(tmp_path) == b"<generated/>"


def test_no_stamp_refuses_and_names_the_generation_step(tmp_path):
    with pytest.raises(SystemExit, match="rr MSS stamp missing.*generated by RouteRTL"):
        _mod().authoritative_xml_bytes(ROOT, tmp_path / "absent.json")


def test_a_stamp_from_another_cfg_refuses(tmp_path):
    with pytest.raises(SystemExit, match="generated from cfg sha256 0{64}, not the tracked"):
        _mod().authoritative_xml_bytes(ROOT, _stamp(tmp_path, cfg_sha256="0" * 64))


def test_a_stamp_naming_a_missing_component_refuses(tmp_path):
    with pytest.raises(SystemExit, match="generated MSS component named by .* is missing"):
        _mod().authoritative_xml_bytes(ROOT, _stamp(tmp_path, cxz=str(tmp_path / "nowhere.cxz")))


@pytest.mark.parametrize("text", ["not json", "{}", '{"cxz": "/x"}', "[]"])
def test_an_unreadable_stamp_refuses(tmp_path, text):
    stamp = tmp_path / "rr_mss_stamp.json"
    stamp.write_text(text)
    with pytest.raises(SystemExit, match="unreadable or lacks cxz/cfg_sha256"):
        _mod().authoritative_xml_bytes(ROOT, stamp)


def test_the_module_names_no_tracked_component_path():
    src = (ROOT / "sw" / "linux" / "pfsoc" / "hss" / "disco_iomux_config.py").read_text()
    assert "_CXZ_RELPATH" not in src
    assert '"disco_mss.cxz"' not in src
