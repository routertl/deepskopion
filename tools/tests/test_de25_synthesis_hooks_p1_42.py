"""DE-F0 (DS-P1.42) regression guard.

The queued bitstream build (rr 4.8.1) never threads ``tcl_hooks.gen_project``
into ``gen_project.tcl``'s ``tcl_files`` argument for the queue/bitstream flow
(confirmed from a --force build's own log: an EMPTY tcl_files arg). A hook
listed ONLY under ``tcl_hooks.gen_project`` therefore never runs there.
``tcl_hooks.synthesis`` IS reliably sourced (a separate g_synthesis_hooks path
in gen_synthesis.tcl), so the fix re-lists the same project-options hook
there as the working channel — this guards that both listings stay in place,
since ``de25_project_options.tcl``'s ``DEVICE_INITIALIZATION_CLOCK``
assignment is silently dropped for the queue flow without the synthesis-side
copy.

DS-P1.52 update: this hook used to ALSO generate the HPS/io96b subsystem via
a hand-authored qsys-script (``de25_hps_subsys.tcl``, sourced from here).
That mechanism is retired — it passed every source-level guard (including
this file's former qip-wiring / scratch-project checks) while still producing
a ``.sof`` with no real HPS partition (quartus_pfg Error 20809). The HPS is
now declared in the project-root ``ip.yml`` (``hps_regenerate: true``,
DS-P2.196) and generated by rr's own pre-synth HPS generator — see
``test_de25_hps_regenerate_ds_p2_196.py`` and
``test_de25_shell_contract.py::test_target_local_generation_and_regenerated_ip``
for that mechanism's guards. This file now only covers the still-live
dual-channel DEVICE_INITIALIZATION_CLOCK gap.
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "targets/de25_datalogger.yml"
PROJECT_OPTIONS_HOOK = "hw/quartus/de25/de25_project_options.tcl"


def _tcl_hooks():
    config = yaml.safe_load(TARGET.read_text())
    return config["tcl_hooks"]


def test_synthesis_hooks_carry_the_working_channel():
    hooks = _tcl_hooks()
    assert PROJECT_OPTIONS_HOOK in hooks.get("synthesis", []), (
        f"{PROJECT_OPTIONS_HOOK} must stay listed under tcl_hooks.synthesis — "
        "that is the only channel the installed rr SDK's queue/bitstream flow "
        "reliably sources for this target; dropping it silently drops the "
        "DEVICE_INITIALIZATION_CLOCK assignment for that flow (DS-P1.42)."
    )


def test_gen_project_hooks_still_declare_the_documented_channel():
    hooks = _tcl_hooks()
    assert PROJECT_OPTIONS_HOOK in hooks.get("gen_project", []), (
        f"{PROJECT_OPTIONS_HOOK} should stay declared under "
        "tcl_hooks.gen_project too — that is the schema-documented channel, "
        "kept so the target picks it back up for free once the upstream rr "
        "gap closes."
    )


def test_project_options_hook_sets_device_initialization_clock():
    text = (ROOT / "hw/quartus/de25/de25_project_options.tcl").read_text()
    assert "DEVICE_INITIALIZATION_CLOCK" in text and "OSC_CLK_1_125MHZ" in text, (
        "de25_project_options.tcl must still set DEVICE_INITIALIZATION_CLOCK "
        "-- this is the platform fact DS-P1.42's dual-channel listing exists "
        "to carry through the queue/bitstream flow."
    )


def test_de25_hps_subsys_hook_stays_retired():
    """DS-P1.52: this hook is not just unused, it must not come back — its
    presence would mean a second, tcl-driven HPS-generation path competing
    with the rr-native one, and it is the exact defect this ticket fixes."""
    assert not (ROOT / "hw/quartus/de25/de25_hps_subsys.tcl").exists()
    text = (ROOT / "hw/quartus/de25/de25_project_options.tcl").read_text()
    assert "de25_hps_subsys.tcl" not in text
