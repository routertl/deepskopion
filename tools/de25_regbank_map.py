#!/usr/bin/env python3
# rr unknown-llm (AI-generated)
"""Generate the DE25 contract's register map: project_regbank.yml as the HPS sees it.

``runtimes/hw.yml`` names the register map routertl's map-access preamble
walks before every REQ (RTL-P2.1213). ``project_regbank.yml`` alone is the
wrong map for that: it declares no ``base_address`` and no ``address_mode``,
so the preamble resolves its byte offsets at physical 0 in word mode
(GIT_HASH 0x0, HEARTBEAT_CNT 0x300) — low HPS memory, not the regbank
(DS-T2.86).

The two declarations cannot go into project_regbank.yml itself: the regbank
generators read ``address_mode`` too, and ``bytes`` changes the generated
RTL (system_regbank.vhd G_ADDR_WIDTH) and the manifest ROM. So this tool
writes a contract-only view, ``runtimes/de25_regbank_map.yml``: the
registers copied unchanged, ``address_mode: bytes``, and ``base_address``
read from the ``ring-watermark@20000000`` node of
``targets/de25_datalogger.yml`` (the CSR aperture the DTB declares).

    python tools/de25_regbank_map.py           # regenerate the view
    python tools/de25_regbank_map.py --check   # exit 1 if it is stale

Exit 0 = view written / fresh, 1 = stale (``--check``).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hw_run_hps_devmem import csr_aperture  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REGBANK = Path("project_regbank.yml")
VIEW = Path("runtimes") / "de25_regbank_map.yml"

HEADER = """\
# GENERATED by tools/de25_regbank_map.py from project_regbank.yml and the
# CSR aperture of targets/de25_datalogger.yml — do not edit; regenerate.
#
# The register map runtimes/hw.yml hands routertl's map-access preamble
# (DS-T2.86): the regbank's byte offsets at the lwh2f regbank base. The
# regbank generators never read this file.
"""


def expected_view(project_root: Path) -> dict:
    regbank = yaml.safe_load((project_root / REGBANK).read_text(encoding="utf-8"))
    base, _span = csr_aperture(project_root)
    return {
        "name": regbank["name"],
        "version": regbank["version"],
        "address_mode": "bytes",
        "base_address": f"0x{base:08X}",
        "registers": regbank["registers"],
    }


def render(view: dict) -> str:
    return HEADER + yaml.safe_dump(view, sort_keys=False, width=100)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--project", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed view differs from a fresh one")
    a = ap.parse_args(argv)
    root = a.project.resolve()
    want = expected_view(root)
    path = root / VIEW
    if a.check:
        have = yaml.safe_load(path.read_text(encoding="utf-8")) if path.is_file() else None
        if have != want:
            print(f"STALE: {VIEW} does not match project_regbank.yml + the "
                  f"CSR aperture; run python tools/de25_regbank_map.py", file=sys.stderr)
            return 1
        print(f"{VIEW} is fresh")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(want), encoding="utf-8")
    print(f"wrote {VIEW}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
