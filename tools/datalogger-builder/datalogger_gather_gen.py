CONFIG_SCHEMA_MAGIC_V02 = 0xC0A1DE02


def _domain_map_from_registry() -> dict:
    """DS-P3.57: protocol-name -> 4-bit domain code, sourced from the canonical
    registry deepskopion/system_ids.yml (single source of truth). Keys are
    upper-cased to match the generator's protocol prefixes; the generator's
    'TIMESTAMP' prefix aliases DOMAIN_SYS (timestamps route through sys). The
    generated RTL is byte-identical to the former hand-kept dict — the active
    build's protocols are a subset, and their codes match the registry (guarded
    by tools/datalogger-builder/tests/test_id_gen.py)."""
    root = Path(__file__).resolve().parents[2]   # repo root holds system_ids.yml
    reg = yaml.safe_load((root / "system_ids.yml").read_text())["domains"]
    m = {name.upper(): int(d["code"]) for name, d in reg.items()}
    m["TIMESTAMP"] = m["SYS"]
    return m


def sanitize_type(name: str) -> str:
    """Normalize protocol names to uppercase constants."""
    return {
        "i2c": "I2C",
        "spi": "SPI",
        "uart": "UART",
        "i2s": "I2S",
        "qspi": "QSPI",
        "quadspi": "QSPI",
        "edge": "EDGE",
        "edgedetection": "EDGE",
        "jtag": "JTAG",
        "mdio": "MDIO",
        "onewire": "ONEWIRE",
        "can": "CAN",
        "timestamp": "TIMESTAMP",
    }.get(name.lower(), name.upper())


def load_board_pins(path: Path | None = None) -> list[dict]:
    """DS-P1.66: deepskopion_core's capture sources, in board_pin index order."""
    path = path or Path(__file__).resolve().parent / "board_pins.yml"
    return load_yaml(path)["board_pins"]


def configured_signals(config: dict) -> list[tuple[str, int, str, int]]:
    """(PROTO, datalogger id, SIGNAL, logical pin) for every configured signal,
    protocols alphabetical, instances by id, signals in config order."""
    parsed = parse_datalogger_config(config)
    signals = []
    for prefix in sorted(parsed["burst_protocols"]):
        instances = parsed["burst_protocols"][prefix]
        for datalogger_id, pin_map in sorted(instances.items(), key=lambda x: int(x[0])):
            for signal, pin in pin_map.items():
                signals.append((prefix, int(datalogger_id), signal.upper(), int(pin)))
    return signals


def allocate_board_pins(config: dict, board_pins: list[dict] | None = None):
    """DS-P1.66: map every logical capture pin the config uses to a board pin.

    The config numbers logical pins freely (the configurator counts 0..N);
    deepskopion_core can only offer the sources in board_pins.yml. Order:
      1. the config's own `BoardPins: {logical: name}` entries;
      2. a free board pin that prefers this PROTO.SIGNAL (the PoC wiring);
      3. a free general pin, those no protocol prefers first.
    Returns ({logical pin: board pin name}, [unwired (PROTO, id, SIGNAL, pin)]).
    A signal left unwired would read constant '0' in the core.
    """
    board_pins = board_pins if board_pins is not None else load_board_pins()
    names = [bp["name"] for bp in board_pins]
    num_pins = int(config.get("Constraints", {}).get("NumDataloggerPins", 64))
    signals = configured_signals(config)
    for prefix, datalogger_id, signal, pin in signals:
        if not 0 <= pin < num_pins:
            raise ValueError(
                f"{prefix} id {datalogger_id} {signal}: logical pin {pin} is outside "
                f"0..{num_pins - 1} (NumDataloggerPins)")

    mapping: dict[int, str] = {}
    used: set[str] = set()
    for pin, name in (config.get("BoardPins") or {}).items():
        if name not in names:
            raise ValueError(f"BoardPins: {name!r} is not a board pin ({', '.join(names)})")
        if name in used:
            raise ValueError(f"BoardPins: board pin {name} is assigned twice")
        mapping[int(pin)] = name
        used.add(name)

    def place(pin: int, candidates) -> None:
        for bp in candidates:
            if bp["name"] not in used:
                mapping[pin] = bp["name"]
                used.add(bp["name"])
                return

    for prefix, _id, signal, pin in signals:
        if pin not in mapping:
            place(pin, [bp for bp in board_pins if bp.get("prefer") == f"{prefix}.{signal}"])
    general = [bp for bp in board_pins if bp.get("general")]
    general = [bp for bp in general if not bp.get("prefer")] + [bp for bp in general if bp.get("prefer")]
    for _prefix, _id, _signal, pin in signals:
        if pin not in mapping:
            place(pin, general)

    unwired = [s for s in signals if s[3] not in mapping]
    return mapping, unwired


def parse_datalogger_config(config: dict) -> dict:
    """Parse the datalogger configuration into a structured format.

    Post-D.4 (2026-05-16): the stream tier was collapsed. The ZS framer
    (zs_msg_framer.vhd) is the single stamping authority; per-protocol
    dataloggers that want batching handle it inside their own entity and
    feed the burst chain. A non-empty `Dataloggers.Stream:` block in
    datalogger_config.yml is now an error — caller must move the protocol
    to `Dataloggers.Burst:` or batch internally.
    """
    result = {
        "design": config.get("Design", "Unknown"),
        "constraints": config.get("Constraints", {}),
        "timesync_id": config.get("Timesync"),
        "stream_protocols": {},
        "burst_protocols": {},
    }

    dataloggers = config.get("Dataloggers", {})

    stream_block = dataloggers.get("Stream") or {}
    if stream_block:
        raise ValueError(
            "datalogger_config.yml: 'Dataloggers.Stream' is not supported "
            "post-D.4 (single-tier arbiter). Move the protocol(s) "
            f"{list(stream_block.keys())} into 'Dataloggers.Burst', or batch "
            "samples inside the datalogger entity before feeding the burst "
            "chain. See deepskopion decisions.json D.4."
        )

    # Burst protocols
    for proto_name, instances in dataloggers.get("Burst", {}).items():
        prefix = sanitize_type(proto_name)
        result["burst_protocols"][prefix] = instances

    return result


def unwired_pins_error(unwired: list[tuple[str, int, str, int]], board_pins: list[dict]) -> str:
    listed = ", ".join(f"{p} id {i} {s} (logical pin {n})" for p, i, s, n in unwired)
    return (
        f"{len(unwired)} configured signal(s) have no deepskopion_core capture source "
        f"left ({len(board_pins)} board pins, board_pins.yml): {listed}. They would "
        f"read constant '0'. Configure fewer signals, or set "
        f"Constraints.AllowUnwiredPins: true to build them unwired on purpose.")


def generate_datalogger_config_pkg(config: dict, protocols_meta: dict,
                                   board_pins: list[dict] | None = None) -> str:
    """Generate datalogger_config_pkg.vhd content."""
    parsed = parse_datalogger_config(config)
    board_pins = board_pins if board_pins is not None else load_board_pins()
    capture_map, unwired = allocate_board_pins(config, board_pins)
    if unwired and not parsed["constraints"].get("AllowUnwiredPins", False):
        raise ValueError(unwired_pins_error(unwired, board_pins))
    lines = []

    # Header
    lines.append("-- Generated by datalogger_gather_gen.py")
    lines.append("-- DO NOT EDIT MANUALLY - Generated from datalogger_config.yml\n")
    lines.append("library ieee;")
    lines.append("use ieee.std_logic_1164.all;")
    lines.append("use ieee.numeric_std.all;")
    lines.append("use ieee.math_real.all;\n")
    lines.append("package datalogger_config_pkg is\n")

    # Constraints
    constraints = parsed["constraints"]
    lines.append(f"  constant C_NUM_DATALOGGER_PINS : integer := {constraints.get('NumDataloggerPins', 64)};")
    lines.append(f"  constant C_MAX_DATALOGGER_ID   : integer := {constraints.get('MaxDataloggerID', 31)};")
    lines.append("")

    # Collect all instances
    all_protocols = {}
    all_protocols.update(parsed["stream_protocols"])
    all_protocols.update(parsed["burst_protocols"])

    # Count dataloggers per type. We emit C_<PROTO>_DATALOGGERS for every
    # protocol listed in protocols.yml — even those absent from this
    # datalogger_config.yml, which get a zero count. That keeps
    # datalogger_pkg.vhd's `C_NUM_DATALOGGERS := C_I2C + C_SPI + ...` sum
    # valid regardless of which subset the user enables.
    lines.append("  -- Datalogger counts per type (always emitted, 0 when absent)")
    known_protocols = sorted(protocols_meta.get("protocols", {}).keys())
    for prefix in known_protocols:
        count = len(all_protocols.get(prefix, {}))
        lines.append(f"  constant C_{prefix}_DATALOGGERS : integer := {count};")

    # Add constants required by datalogger_pkg.vhd but not yet protocol-driven
    lines.append("  -- Non-protocol datalogger types (required by datalogger_pkg.vhd)")
    lines.append("  constant C_LEVEL_DRIVERS : integer := 0;  -- Level injection not yet implemented")
    timestamp_count = 1 if parsed["timesync_id"] is not None else 0
    lines.append(f"  constant C_TIMESTAMP_SYNCS : integer := {timestamp_count};")
    lines.append("")

    # Datalogger IDs
    lines.append("  -- Datalogger instance IDs")
    id_to_const = []
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        for idx, (datalogger_id, _) in enumerate(sorted(instances.items(), key=lambda x: int(x[0]))):
            const_name = f"C_{prefix}{idx}_ID"
            id_to_const.append((int(datalogger_id), const_name, prefix, idx))

    for datalogger_id, const_name, _, _ in sorted(id_to_const, key=lambda x: x[0]):
        lines.append(f"  constant {const_name:<20} : natural := {datalogger_id};")

    # Timesync
    if parsed["timesync_id"] is not None:
        lines.append(f"  constant C_TIMESYNC_ID         : natural := {parsed['timesync_id']};")
    lines.append("")

    # Pin constants
    lines.append("  -- Datalogger logical pin mappings")
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        for idx, (datalogger_id, pin_map) in enumerate(sorted(instances.items(), key=lambda x: int(x[0]))):
            for signal, pin in pin_map.items():
                const_name = f"C_{prefix}{idx}_{signal.upper()}"
                lines.append(f"  constant {const_name:<24} : integer := {pin};")
    lines.append("")

    # DS-P1.66: the generator owns the logical-pin -> board-pin map.
    # deepskopion_core builds board_pin(C_BOARD_PIN_<name>) from its PMOD /
    # EMIO / tap sources and drives capture_pin(i) <= board_pin(
    # C_CAPTURE_BOARD_PIN(i)), so every configured logical pin is wired to
    # the source allocated here, whatever number the config gave it.
    lines.append("  -- Board pins: deepskopion_core capture sources (DS-P1.66, board_pins.yml)")
    for idx, bp in enumerate(board_pins):
        lines.append(f"  constant C_BOARD_PIN_{bp['name']:<8} : natural := {idx};")
    lines.append(f"  constant C_NUM_BOARD_PINS     : natural := {len(board_pins)};")
    lines.append("  constant C_BOARD_PIN_NONE     : natural := C_NUM_BOARD_PINS;  -- logical pin not wired")
    lines.append("")
    lines.append("  -- Logical capture pin -> board pin (DS-P1.66, allocated by the generator)")
    lines.append("  type t_capture_board_map is array (0 to C_NUM_DATALOGGER_PINS - 1) of natural;")
    owner = {pin: f"{p} id {i} {s}" for p, i, s, pin in reversed(configured_signals(config))}
    lines.append("  constant C_CAPTURE_BOARD_PIN : t_capture_board_map := (")
    for pin in sorted(capture_map):
        lines.append(f"    {pin:>2} => C_BOARD_PIN_{capture_map[pin] + ',':<9} -- {owner.get(pin, '')}".rstrip())
    lines.append("    others => C_BOARD_PIN_NONE);")
    for prefix, datalogger_id, signal, pin in unwired:
        lines.append(f"  -- UNWIRED (AllowUnwiredPins): {prefix} id {datalogger_id} {signal}, logical pin {pin}")
    lines.append("")

    # Pins per type
    lines.append("  -- Number of pins per datalogger type")
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        if instances:
            first_instance = next(iter(instances.values()))
            pin_count = len(first_instance)
            lines.append(f"  constant C_{prefix}_PINS : integer := {pin_count};")
    lines.append("")

    # Max line frequency per type (DS-T3.5 — sizes the per-pin glitch_filter
    # window in the gather; see protocols.yml `max_freq_hz`). Emitted for every
    # active protocol so the gather can reference C_<PROTO>_MAX_FREQ_HZ
    # unconditionally. Undeclared protocols fall back to DEFAULT_MAX_FREQ_HZ
    # (high → pure synchroniser, never eats real edges).
    lines.append("  -- Max line frequency per datalogger type (DS-T3.5 input conditioning)")
    proto_meta = protocols_meta.get("protocols", {})
    for prefix in sorted(all_protocols.keys()):
        max_freq = proto_meta.get(prefix, {}).get("max_freq_hz", DEFAULT_MAX_FREQ_HZ)
        lines.append(f"  constant C_{prefix}_MAX_FREQ_HZ : positive := {int(max_freq)};")
    lines.append("")

    # DS-P3.117: EDGE max-frequency register width — single source of truth shared
    # by the edge_datalogger G_MAXFREQ_WIDTH (set in protocols.yml), the gather's
    # EDGE_MAX_IVALS port slicing, and the maxfreq_event_bank G_IVAL_WIDTH in
    # deepskopion_top.
    edge_meta = proto_meta.get("EDGE", {})
    mf_width = int(edge_meta.get("maxfreq_width", 24))
    lines.append("  -- EDGE max-frequency min-interval register width (DS-P3.117)")
    lines.append(f"  constant C_EDGE_MAXFREQ_WIDTH : integer := {mf_width};")
    lines.append("")

    # Pin arrays (type declarations)
    lines.append("  -- Pin mapping types")
    lines.append("  type t_pin_mapping is array (natural range <>) of natural;")
    lines.append("")

    # Per-instance pin constants
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        lines.append(f"  -- {prefix} pin mappings")
        for idx, (datalogger_id, pin_map) in enumerate(sorted(instances.items(), key=lambda x: int(x[0]))):
            signal_consts = [f"C_{prefix}{idx}_{s.upper()}" for s in pin_map.keys()]
            joined = ", ".join(reversed(signal_consts))
            pin_count = len(signal_consts)
            if pin_count > 1:
                lines.append(f"  constant C_{prefix}{idx}_PINS : t_pin_mapping({pin_count-1} downto 0) := ({joined});")
            else:
                lines.append(f"  constant C_{prefix}{idx}_PINS : t_pin_mapping(0 downto 0) := (0 => {signal_consts[0]});")
        lines.append("")

    # Pin array types
    lines.append("  -- Interface-wide pin arrays")
    for prefix in sorted(all_protocols.keys()):
        count = len(all_protocols[prefix])
        lines.append(f"  type t_{prefix.lower()}_pinmap_array is array(0 to C_{prefix}_DATALOGGERS - 1) of t_pin_mapping;")
    lines.append("")

    # Pin array constants
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        pins_list = [f"C_{prefix}{idx}_PINS" for idx in range(len(instances))]
        joined = ", ".join(pins_list)
        if len(pins_list) > 1:
            lines.append(f"  constant C_{prefix}_PIN_ARRAY : t_{prefix.lower()}_pinmap_array := ({joined});")
        else:
            lines.append(f"  constant C_{prefix}_PIN_ARRAY : t_{prefix.lower()}_pinmap_array := (0 => {pins_list[0]});")
    lines.append("")

    protocols_list = [p for p in known_protocols if p != "TIMESTAMP"]

    # ID types and arrays
    lines.append("  -- Datalogger instance ID types per type")
    for prefix in sorted(all_protocols.keys()):
        count = len(all_protocols[prefix])
        lines.append(f"  type t_{prefix.lower()}Index is array(0 to {count-1}) of natural;")
    for prefix in protocols_list:
        if prefix not in all_protocols:
            lines.append(f"  type t_{prefix.lower()}Index is array(0 to 0) of natural;")
    lines.append("")

    lines.append("  -- Datalogger instance ID constants per type")
    for prefix in sorted(all_protocols.keys()):
        instances = all_protocols[prefix]
        id_consts = [f"C_{prefix}{idx}_ID" for idx in range(len(instances))]
        joined = ", ".join(id_consts)
        if len(id_consts) > 1:
            lines.append(f"  constant C_{prefix}_IDS : t_{prefix.lower()}Index := ({joined});")
        else:
            lines.append(f"  constant C_{prefix}_IDS : t_{prefix.lower()}Index := (0 => {id_consts[0]});")
    for prefix in protocols_list:
        if prefix not in all_protocols:
            lines.append(f"  constant C_{prefix}_IDS : t_{prefix.lower()}Index := (0 => 0);")
    lines.append("")

    # Per-protocol telemetry counter indexes — one slot per active
    # protocol (burst + stream union), sorted alphabetical. Drives
    # the PROTO_COUNTERS array on datalogger_gather (DS-P3.26).
    lines.append("  -- Per-protocol telemetry counter indexes (DS-P3.26)")
    proto_idx_names = sorted(all_protocols.keys())
    for idx, prefix in enumerate(proto_idx_names):
        lines.append(f"  constant C_PROTO_IDX_{prefix:<6}: natural := {idx};")
    for prefix in protocols_list:
        if prefix not in all_protocols:
            lines.append(f"  constant C_PROTO_IDX_{prefix:<6}: natural := 0;")
    lines.append(f"  constant C_NUM_PROTO_COUNTERS : natural := {len(proto_idx_names)};")
    lines.append("")

    # Per-protocol ZS-msg domain codes — used by datalogger_gather to stamp
    # the msg_type field of each tuple flowing through the chain
    # (DS-P3.29). The 4-bit domain code is the middle nibble of msg_type:
    # msg_type[11:8]. Map matches zs_msg_pkg.C_ZS_DOMAIN_* constants.
    lines.append("  -- Per-protocol ZS-msg domain codes (DS-P3.29)")
    # DS-P3.57: SOURCED from system_ids.yml (single source of truth), not a
    # hand-kept dict. Output stays byte-identical (same codes, active subset).
    _domain_map = _domain_map_from_registry()
    for prefix in sorted(set(proto_idx_names + protocols_list)):
        code = _domain_map.get(prefix, 0x0)
        lines.append(
            f'  constant C_DOMAIN_{prefix:<6}: std_logic_vector(3 downto 0) := X"{code:1X}";'
        )
    lines.append("")

    # Arbiter indexes
    stream_count = sum(len(v) for v in parsed["stream_protocols"].values())
    burst_types = list(parsed["burst_protocols"].keys())
    if parsed["timesync_id"] is not None:
        burst_types.append("TIMESTAMP")
    burst_types = sorted(set(burst_types))

    lines.append("  -- Stream interface indexes per datalogger instance")
    stream_idx = 0
    for prefix in sorted(parsed["stream_protocols"].keys()):
        instances = parsed["stream_protocols"][prefix]
        for idx in range(len(instances)):
            lines.append(f"  constant C_STREAM_{prefix}{idx}_INDEX : natural := {stream_idx};")
            stream_idx += 1
    lines.append("")

    lines.append("  -- Burst interface indexes per datalogger type")
    for idx, prefix in enumerate(burst_types):
        lines.append(f"  constant C_ARB_{prefix}_INDEX : natural := {idx};")
    lines.append("")

    lines.append("  -- Datalogger type counters")
    lines.append(f"  constant C_NUM_STREAMS : integer := {stream_count};")
    lines.append(f"  constant C_NUM_ARB_INPUTS  : integer := {len(burst_types)};")
    if stream_count > 0:
        lines.append(f"  constant C_STREAM_IDWIDTH : integer := integer(ceil(log2(real(C_NUM_STREAMS))));")
    else:
        lines.append(f"  constant C_STREAM_IDWIDTH : integer := 1;")
    if len(burst_types) > 0:
        lines.append(f"  constant C_ARB_IF_IDWIDTH : integer := integer(ceil(log2(real(C_NUM_ARB_INPUTS))));")
    else:
        lines.append(f"  constant C_ARB_IF_IDWIDTH : integer := 1;")
    lines.append("")

    # Grouped index arrays. Single-element aggregates need named
    # association (`(0 => X)`) — positional `(X)` is ambiguous with
    # a parenthesised scalar expression and Vivado synth errors with
    # `[Synth 8-10097] type error … current type natural; expected
    # type t_burst_index_array`.
    lines.append("  -- Grouped index arrays")
    if burst_types:
        lines.append(f"  type t_burst_index_array is array(0 to {len(burst_types)-1}) of natural;")
        if len(burst_types) == 1:
            lines.append(f"  constant C_ARB_INDEXES : t_burst_index_array := (0 => C_ARB_{burst_types[0]}_INDEX);")
        else:
            joined = ", ".join(f"C_ARB_{t}_INDEX" for t in burst_types)
            lines.append(f"  constant C_ARB_INDEXES : t_burst_index_array := ({joined});")
    lines.append("")

    for prefix in sorted(parsed["stream_protocols"].keys()):
        count = len(parsed["stream_protocols"][prefix])
        lines.append(f"  type t_stream_{prefix.lower()}_index_array is array(0 to {count-1}) of natural;")
        if count == 1:
            lines.append(f"  constant C_STREAM_{prefix}_INDEXES : t_stream_{prefix.lower()}_index_array := (0 => C_STREAM_{prefix}0_INDEX);")
        else:
            joined = ", ".join(f"C_STREAM_{prefix}{i}_INDEX" for i in range(count))
            lines.append(f"  constant C_STREAM_{prefix}_INDEXES : t_stream_{prefix.lower()}_index_array := ({joined});")
    lines.append("")

    # Footer
    lines.append("end package datalogger_config_pkg;")
    lines.append("")
    lines.append("package body datalogger_config_pkg is")
    lines.append("end datalogger_config_pkg;")
    lines.append("")

    return "\n".join(lines)


def generate_datalogger_gather(config: dict, protocols_meta: dict, template_dir: Path) -> str:
    """Generate datalogger_gather.vhd using Jinja2 template."""
    parsed = parse_datalogger_config(config)

    # Build protocol data with metadata from protocols.yml
    burst_protocols = {}
    for proto_name, instances in parsed["burst_protocols"].items():
        if proto_name in protocols_meta.get("protocols", {}):
            proto_data = protocols_meta["protocols"][proto_name].copy()
            proto_data["count"] = len(instances)
            burst_protocols[proto_name] = proto_data

    stream_protocols = {}
    for proto_name, instances in parsed["stream_protocols"].items():
        if proto_name in protocols_meta.get("protocols", {}):
            proto_data = protocols_meta["protocols"][proto_name].copy()
            proto_data["count"] = len(instances)
            stream_protocols[proto_name] = proto_data

    # Setup Jinja2 environment
    env = Environment(
        loader=FileSystemLoader(template_dir),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )

    template = env.get_template("datalogger_gather.vhd.j2")

    # Combined view (sorted alphabetical) — used by the template for the
    # per-protocol PKT/ERR counter scaffolding (DS-P3.26). Keys are the
    # canonical uppercase protocol names; values just need .count for now.
    all_protocols = {}
    for name, data in burst_protocols.items():
        all_protocols[name] = data
    for name, data in stream_protocols.items():
        all_protocols[name] = data
    all_protocols_sorted = {k: all_protocols[k] for k in sorted(all_protocols.keys())}

    # Render template
    return template.render(
        design=parsed["design"],
        burst_protocols=burst_protocols,
        stream_protocols=stream_protocols,
        all_protocols=all_protocols_sorted,
        timesync_id=parsed["timesync_id"],
    )


def generate_config_schema_hex(config: dict, protocols_meta: dict) -> str:
    """Generate config_schema.hex — one 32-bit word per line.

    v02 encoding (deepskopion-side; routertl is unaware):

        word 0   : magic 0xC0A1DE02  (CONFIG-vDE02 — "configured" v02)
        word 1   : total_instance_count
        word 2.. : one word per datalogger instance, layout:
                    [31:24] protocol_id  (system_ids.yml domain code: uart=1, i2c=2, ...)
                    [23:16] datalogger_id   (per datalogger_config.yml)
                    [15:8 ] pin_count    (signals per instance)
                    [7:0  ] flags        (reserved, currently 0)

    v01 (magic 0xC0A1DE01, every bitstream built before DS-P2.162) wrote protocol_id
    as the alphabetical index of the protocols (edge=0, i2c=1, jtag=2, spi=3,
    uart=4). The two are NOT interchangeable, which is why the magic changed;
    sw/stream/arm_datalogger_defaults.py decodes both and refuses any other magic.

    PS firmware reads the file via the system_regbank_wrapper streaming
    pattern (read CONFIG_NUM_WORDS to reset the pointer, then read
    CONFIG_DATA N times to drain). Protocol-name lookup is via
    datalogger_config_pkg.vhd at synth time + a parallel Python constants
    table at SW side.
    """
    parsed = parse_datalogger_config(config)
    lines: list[str] = []

    # Header
    lines.append(f"{CONFIG_SCHEMA_MAGIC_V02:08x}")

    # All protocol instances, sorted-prefix order (deterministic across builds)
    all_protocols = {}
    all_protocols.update(parsed["stream_protocols"])
    all_protocols.update(parsed["burst_protocols"])

    domain_map = _domain_map_from_registry()

    total = sum(len(insts) for insts in all_protocols.values())
    lines.append(f"{total:08x}")

    for prefix in sorted(all_protocols.keys()):
        proto_id = domain_map.get(prefix.upper(), 0xFF)
        instances = all_protocols[prefix]
        # First instance's pin count is representative — pin maps are
        # uniform per protocol (e.g. I2C is always 2 signals).
        if instances:
            pin_count = len(next(iter(instances.values())))
        else:
            pin_count = 0
        for datalogger_id, _ in sorted(instances.items(), key=lambda x: int(x[0])):
            word = (
                ((proto_id & 0xff) << 24)
                | ((int(datalogger_id) & 0xff) << 16)
                | ((pin_count & 0xff) << 8)
                | (0 & 0xff)  # flags
            )
            lines.append(f"{word:08x}")

    return "\n".join(lines) + "\n"


def check_and_acquire_mix_lock(config_path: Path, config: dict, lock_path: Path | None = None) -> Path:
    """DS-P2.163: Guard against concurrent builds of different mixes corrupting shared VHDL.

    When concurrent builds of disparate mixes run in the same worktree, their pre-build
    generation overwrites the shared in-tree VHDL (datalogger_gather.vhd, datalogger_config_pkg.vhd).
    If another live build process is using the shared tree for a different mix, this check
    raises RuntimeError to refuse the concurrent corruption.
    """
    root = Path(__file__).resolve().parents[2]
    lock_file = lock_path if lock_path is not None else (root / ".routertl_cache" / "datalogger_mix_build.lock")
    lock_file.parent.mkdir(parents=True, exist_ok=True)

    summary = {}
    for proto, instances in (config.get("Dataloggers", {}).get("Burst", {}) or {}).items():
        summary[proto.lower()] = len(instances)

    if lock_file.is_file():
        try:
            data = json.loads(lock_file.read_text(encoding="utf-8"))
            active_pid = data.get("parent_pid") or data.get("pid")
            locked_summary = data.get("summary", {})
            locked_cfg = data.get("config_name", "")

            # Check if recorded process is still running
            pid_alive = False
            if isinstance(active_pid, int) and active_pid > 0:
                try:
                    os.kill(active_pid, 0)
                    pid_alive = True
                except ProcessLookupError:
                    pid_alive = False
                except PermissionError:
                    pid_alive = True

            current_pids = {os.getpid(), os.getppid()}
            if pid_alive and active_pid not in current_pids and locked_summary != summary:
                raise RuntimeError(
                    f"Concurrent build conflict: another active build (PID {active_pid}) is using "
                    f"shared in-tree datalogger VHDL for mix {locked_summary} ({locked_cfg}). "
                    f"Concurrent builds of different mixes in the same worktree corrupt shared RTL. "
                    f"Wait for PID {active_pid} to complete or isolate the build."
                )
        except RuntimeError:
            raise
        except (json.JSONDecodeError, OSError):
            pass

    # Record our active mix and process identity
    lock_data = {
        "pid": os.getpid(),
        "parent_pid": os.getppid(),
        "config": str(config_path),
        "config_name": config_path.name,
        "summary": summary,
        "timestamp": time.time(),
    }
    lock_file.write_text(json.dumps(lock_data, indent=2), encoding="utf-8")
    return lock_file


def writes_in_tree(out_dirs, root: Path | None = None) -> bool:
    """True when any output directory resolves inside the repository.

    The DS-P2.163 mix lock protects the shared in-tree VHDL. A run whose
    outputs all lie outside the tree (a test or a user generating into a
    scratch dir) writes none of it, so it neither takes nor honours the lock."""
    root = (root if root is not None else Path(__file__).resolve().parents[2]).resolve()
    for out in out_dirs:
        if out is None:
            continue
        try:
            Path(out).resolve().relative_to(root)
            return True
        except ValueError:
            continue
    return False


def release_mix_lock(lock_path: Path | None = None) -> None:
    """Release the datalogger mix build lock if held by this process or its parent."""
    root = Path(__file__).resolve().parents[2]
    lock_file = lock_path if lock_path is not None else (root / ".routertl_cache" / "datalogger_mix_build.lock")
    if lock_file.is_file():
        try:
            data = json.loads(lock_file.read_text(encoding="utf-8"))
            current_pids = {os.getpid(), os.getppid()}
            if data.get("pid") in current_pids or data.get("parent_pid") in current_pids:
                lock_file.unlink(missing_ok=True)
        except Exception:
            pass


def main():
    parser = argparse.ArgumentParser(description="Generate datalogger VHDL from YAML config")
    parser.add_argument("config", help="Path to datalogger_config.yml")
    parser.add_argument("--protocols", default=None, help="Path to protocols.yml (default: same dir as script)")
    parser.add_argument("--pkg-dir", default="./pkg", help="Output directory for datalogger_config_pkg.vhd")
    parser.add_argument("--rtl-dir", default="./datalogger/infra", help="Output directory for datalogger_gather.vhd")
    parser.add_argument("--board-pins", default=None,
                        help="Path to board_pins.yml (default: same dir as script)")
    parser.add_argument("--regbank-dir", default=None, help="Output directory for config_schema.hex (default: skip)")
    args = parser.parse_args()

    script_dir = Path(__file__).parent
    config_path = Path(args.config)
    pkg_dir = Path(args.pkg_dir)
    rtl_dir = Path(args.rtl_dir)
    template_dir = script_dir / "templates"

    # Load configurations
    config = load_yaml(config_path)
    protocols_path = Path(args.protocols) if args.protocols else script_dir / "protocols.yml"
    protocols = load_yaml(protocols_path)

    # DS-P2.163: Guard against concurrent builds of conflicting mixes corrupting
    # shared VHDL. Only a run that writes into the tree can corrupt it.
    if writes_in_tree((pkg_dir, rtl_dir, args.regbank_dir)):
        try:
            check_and_acquire_mix_lock(config_path, config)
        except RuntimeError as err:
            raise SystemExit(f"❌ {err}")

    # Generate package. DS-P1.66: a config whose signals the core cannot wire
    # is refused here, before any file is written.
    board_pins = load_board_pins(Path(args.board_pins) if args.board_pins else None)
    try:
        pkg_content = generate_datalogger_config_pkg(config, protocols, board_pins)
    except ValueError as err:
        raise SystemExit(f"❌ {config_path}: {err}")
    pkg_path = pkg_dir / "datalogger_config_pkg.vhd"
    write_if_changed(pkg_path, pkg_content)
    print(f"✅ Generated {pkg_path}")

    # Generate RTL module
    rtl_content = generate_datalogger_gather(config, protocols, template_dir)
    rtl_path = rtl_dir / "datalogger_gather.vhd"
    write_if_changed(rtl_path, rtl_content)
    print(f"✅ Generated {rtl_path}")

    # Generate config_schema.hex if a regbank dir was provided. This is
    # the BRAM-init payload PS firmware streams out via the
    # system_regbank_wrapper CONFIG_DATA register (read CONFIG_NUM_WORDS
    # to reset pointer, then read CONFIG_DATA N times to drain).
    if args.regbank_dir:
        cfg_hex = generate_config_schema_hex(config, protocols)
        cfg_path = Path(args.regbank_dir) / "config_schema.hex"
        write_if_changed(cfg_path, cfg_hex)
        print(f"✅ Generated {cfg_path}")

    # DS-P3.57: gate the build on id-registry drift. The gather generated above is
    # registry-sourced (cannot drift); this checks the OTHER domain copies
    # (sw/stream/zs_msg.py + hw/rtl/pkg/zs_msg_pkg.vhd C_ZS_DOMAIN_*) against
    # system_ids.yml, so a hand-edit that diverges fails the build with a clear
    # message instead of silently shipping an inconsistent id-space.
    import id_gen  # same dir (sys.path[0] = this script's dir when run directly)
    root = id_gen._repo_root(Path(__file__).resolve().parent)
    rc = id_gen.check(root)
    if rc:
        raise SystemExit(rc)

    # DS-P3.59: same gate for the per-protocol decoder codes — sw/stream/
    # protocol_codes.py must match the *_datalogger_protocol.yml contracts, so a
    # message-type/event-code typo can't desync the YAML from the SW decoders.
    import protocol_codes_gen
    rc = protocol_codes_gen.check(root)
    if rc:
        raise SystemExit(rc)


if __name__ == "__main__":
    main()
