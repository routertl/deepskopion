# DS-P3.141: matches the generation-date stamp emitted into both outputs
# ("-- Generated by datalogger_gather_gen.py @ 2026-08-03" in the pkg header,
# "-- Generated  : 2026-08-03" in the gather.vhd template) so write_if_changed
# can diff on SUBSTANCE, not on today's date.
_STAMP_DATE_RE = re.compile(r"^(-- Generated.*?)\d{4}-\d{2}-\d{2}$", re.MULTILINE)


# DS-T3.5: fallback max-frequency for a protocol that omits `max_freq_hz` in
# protocols.yml. Chosen HIGH on purpose — a high frequency floors the glitch
# window at 2 (a pure 2-FF synchroniser), so an undeclared protocol is never
# over-filtered (its real edges are never eaten). The trade-off is no glitch
# rejection for a slow undeclared line; declare `max_freq_hz` to opt into it.
DEFAULT_MAX_FREQ_HZ = 50_000_000


def load_yaml(path: Path) -> dict:
    """Load a YAML file."""
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def _normalize_stamp(content: str) -> str:
    """Blank out the generation-date stamp so two renders that differ ONLY
    in today's date compare equal (DS-P3.141)."""
    return _STAMP_DATE_RE.sub(r"\1", content)


def write_if_changed(path: Path, content: str) -> bool:
    """RTL-P3.1038 + DS-P3.141: write only when content changed MODULO the
    generation-date stamp, so a byte-identical (substance-wise) regen does
    NOT bump the output's mtime/bytes just because it ran on a different
    day — which would falsely trip mtime- and content-hash-based staleness
    gates across separate synth/impl/bitstream stages. Returns True if
    written, False if skipped."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        existing = path.read_text(encoding="utf-8")
        if _normalize_stamp(existing) == _normalize_stamp(content):
            return False
    except (FileNotFoundError, UnicodeDecodeError):
        pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


