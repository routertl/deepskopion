"""Regression guard for DS-P3.141: a no-op regen must not rewrite generated
VHDL just because today's date differs from the date baked into the file's
last run.

datalogger_gather_gen.py stamps `-- Generated ... @ <today>` into both
datalogger_config_pkg.vhd and datalogger_gather.vhd. write_if_changed() used to
compare raw bytes, so a byte-identical (substance-wise) regen on a later day
still rewrote the file, bumping its mtime and dirtying git — which then
tripped downstream content-hash / mtime staleness gates on an unchanged
design (the false "build inputs changed since the artifact was built" seen
while deploying DS-P2.77). It must now diff on substance, modulo the stamp.
"""
import sys
from pathlib import Path

import yaml

_SB = Path(__file__).resolve().parents[1]  # tools/datalogger-builder
sys.path.insert(0, str(_SB))
import datalogger_gather_gen as sgg  # noqa: E402
from datalogger_gather_gen import _STAMP_DATE_RE  # noqa: E402

_ROOT = _SB.parents[1]
_CONFIG = yaml.safe_load((_SB / "config" / "datalogger_config.yml").read_text(encoding="utf-8"))
_PROTOCOLS = yaml.safe_load((_SB / "protocols.yml").read_text(encoding="utf-8"))


def test_normalize_stamp_ignores_only_the_date():
    a = "-- Generated by datalogger_gather_gen.py @ 2026-07-03\nfoo\n"
    b = "-- Generated by datalogger_gather_gen.py @ 2026-08-03\nfoo\n"
    assert sgg._normalize_stamp(a) == sgg._normalize_stamp(b)

    c = "-- Generated  : 2026-07-03\nfoo\n"
    d = "-- Generated  : 2026-08-03\nfoo\n"
    assert sgg._normalize_stamp(c) == sgg._normalize_stamp(d)

    # a real substance change must still be caught
    assert sgg._normalize_stamp(a) != sgg._normalize_stamp(b.replace("foo", "bar"))


def test_write_if_changed_skips_stamp_only_diff(tmp_path):
    path = tmp_path / "datalogger_config_pkg.vhd"
    old = "-- Generated by datalogger_gather_gen.py @ 2026-07-03\n-- DO NOT EDIT MANUALLY\nbody\n"
    new = "-- Generated by datalogger_gather_gen.py @ 2026-08-03\n-- DO NOT EDIT MANUALLY\nbody\n"
    path.write_text(old, encoding="utf-8")
    mtime_before = path.stat().st_mtime_ns

    assert sgg.write_if_changed(path, new) is False
    assert path.stat().st_mtime_ns == mtime_before
    assert path.read_text(encoding="utf-8") == old  # untouched, stamp NOT bumped


def test_write_if_changed_still_writes_on_real_change(tmp_path):
    path = tmp_path / "datalogger_config_pkg.vhd"
    old = "-- Generated by datalogger_gather_gen.py @ 2026-07-03\nbody v1\n"
    new = "-- Generated by datalogger_gather_gen.py @ 2026-08-03\nbody v2\n"
    path.write_text(old, encoding="utf-8")

    assert sgg.write_if_changed(path, new) is True
    assert path.read_text(encoding="utf-8") == new


def test_regen_twice_is_a_true_noop(tmp_path):
    """The ticket's own repro: an unchanged spec regenerated on two different
    days must leave the output file byte-identical, with its mtime unmoved on
    the second run — even though each render stamps "today"."""
    pkg_path = tmp_path / "datalogger_config_pkg.vhd"

    # Simulate a first run that happened on an earlier date than "today".
    content_today = sgg.generate_datalogger_config_pkg(_CONFIG, _PROTOCOLS)
    content_yesterday = _STAMP_DATE_RE.sub(
        lambda m: m.group(1) + "2000-01-01", content_today
    )
    pkg_path.write_text(content_yesterday, encoding="utf-8")
    mtime_before = pkg_path.stat().st_mtime_ns

    # Regen "today": substance is identical, only the stamp date differs.
    written = sgg.write_if_changed(pkg_path, content_today)

    assert written is False
    assert pkg_path.stat().st_mtime_ns == mtime_before
    assert pkg_path.read_bytes() == content_yesterday.encode("utf-8")
