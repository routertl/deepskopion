"""Single-source the daemon's per-protocol STATS identity set from the canonical
datalogger registry (LT-P3.250 / DS-P3.120).

RouteWave's Mission Control PER-PROTOCOL panel must track the ACTUAL datalogger
set. The drift it was filed for: the daemon (data_source.read_regbank_stats)
hardcoded {i2c, spi, uart, qspi, edge, i2s} and RouteWave hardcoded the same six
rows — so it showed stale `i2s` (not an active datalogger) and was MISSING `can`
(DS-P3.100) / `jtag` (DS-P3.56). Both are now active dataloggers in
`tools/datalogger-builder/config/datalogger_config.yml`.

This makes the active protocol IDENTITY set single-sourced from that YAML — the
SAME alphabetical source `datalogger_gather_gen.py` uses (`sanitize_type` of each
`Dataloggers.Burst` block name, then `sorted`). It emits `sw/stream/
datalogger_registry.py` (the ordered protocol list + which protocols have a regbank
counter slot) and a check() drift-gate, mirroring `protocol_codes_gen.py`.

The daemon's STATS frame then emits a self-describing `proto_stats` map keyed by
EVERY active protocol; a protocol WITH a regbank counter slot reports its real
value, one WITHOUT (CAN/JTAG today — their proto_counters are never fanned into
a regbank slot in deepskopion_top.vhd, DS-T2.56) reports null → RouteWave
renders "n/a" (truthful, like arb_grants), never a fabricated number.

Usage:
  datalogger_registry_gen.py gen      # regenerate sw/stream/datalogger_registry.py
  datalogger_registry_gen.py check    # exit 1 if the generated file is stale (drift)
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

_GEN_PATH = Path("sw/stream/datalogger_registry.py")
_CONFIG = Path("tools/datalogger-builder/config/datalogger_config.yml")

# Mirror datalogger_gather_gen.sanitize_type EXACTLY (the canonical name map). Keep
# the two in step — a drift here re-introduces the very bug this gate prevents.
_SANITIZE = {
    "i2c": "I2C",
    "spi": "SPI",
    "uart": "UART",
    "i2s": "I2S",
    "qspi": "QSPI",
    "quadspi": "QSPI",
    "edge": "EDGE",
    "edgedetection": "EDGE",
    "jtag": "JTAG",
    "mdio": "MDIO",
    "onewire": "ONEWIRE",
    "can": "CAN",
    "timestamp": "TIMESTAMP",
}

_HEADER = (
    '"""GENERATED by tools/datalogger-builder/datalogger_registry_gen.py '
    "(LT-P3.250 / DS-P3.120) — DO NOT EDIT.\n\n"
    "The ORDERED active-protocol identity set + per-protocol regbank-slot\n"
    "availability, single-sourced from tools/datalogger-builder/config/\n"
    "datalogger_config.yml (the same source datalogger_gather_gen.py uses). The\n"
    "daemon's wave_stream STATS frame emits a self-describing per-protocol map\n"
    "keyed by ACTIVE_PROTOCOLS; HAS_PKT/HAS_ERR/HAS_DROP say which carry a real\n"
    "regbank counter (the rest report null -> RouteWave renders 'n/a').\n\n"
    "Regenerate with `python3 tools/datalogger-builder/datalogger_registry_gen.py "
    "gen`;\nthe datalogger-builder pre_build hook + test_datalogger_registry_drift.py "
    "gate it.\n"
    '"""\n'
)


def _repo_root(start: Path) -> Path:
    p = start.resolve()
    for cand in (p, *p.parents):
        if (cand / "tools" / "datalogger-builder" / "config" / "datalogger_config.yml").is_file():
            return cand
    raise SystemExit("datalogger_registry_gen: can't find repo root (datalogger_config.yml)")


def _sanitize(name: str) -> str:
    return _SANITIZE.get(name.lower(), name.upper())


def active_protocols(config: dict) -> list[str]:
    """The ordered (alphabetical, canonical-cased) active protocol set —
    mirrors datalogger_gather_gen.parse_datalogger_config + sorted(all_protocols.keys()).
    Only `Dataloggers.Burst` instances count (D.4: single-tier; Stream unsupported)."""
    burst = config.get("Dataloggers", {}).get("Burst", {})
    return sorted({_sanitize(name) for name in burst})


def _slot_availability(root: Path, protos: list[str]) -> dict:
    """For each protocol, which of PKT/ERR/DROP counter slots exist in the
    regbank (sw/stream/regbank.py Regs.*_CNT_<PROTO>). A protocol with no slot
    (CAN/JTAG today) reports null for that field."""
    # Import the regbank Regs to read the actual slot set — the authoritative
    # answer, immune to a stale hardcoded list here.
    sys.path.insert(0, str(root / "sw" / "stream"))
    try:
        from regbank import Regs  # type: ignore
    finally:
        sys.path.pop(0)
    names = set(dir(Regs))
    out = {}
    for p in protos:
        out[p] = {
            "pkts": f"PKT_CNT_{p}" in names,
            "errs": f"ERR_CNT_{p}" in names,
            "drops": f"DROP_CNT_{p}" in names,
        }
    return out


def _render(root: Path) -> str:
    config = yaml.safe_load((root / _CONFIG).read_text(encoding="utf-8"))
    protos = active_protocols(config)
    avail = _slot_availability(root, protos)
    # Wire / consumer-facing canonical names are LOWERCASE (matching the
    # DeriveProtocol labels lowercased + the existing proto_pkts keys).
    names_lc = [p.lower() for p in protos]
    out = [_HEADER]
    out.append("# Ordered active-protocol identity set (canonical lowercase names).")
    out.append("ACTIVE_PROTOCOLS = [")
    for n in names_lc:
        out.append(f"    {n!r},")
    out.append("]\n")
    out.append("# proto -> the regbank Regs.* slot suffix (UPPER) for counter reads.")
    out.append("REGBANK_SUFFIX = {")
    for n, p in zip(names_lc, protos):
        out.append(f"    {n!r}: {p!r},")
    out.append("}\n")
    out.append("# proto -> {pkts,errs,drops}: True = a real regbank counter slot exists;")
    out.append("# False = no slot (report null -> consumer renders 'n/a').")
    out.append("SLOTS = {")
    for n, p in zip(names_lc, protos):
        a = avail[p]
        out.append(
            f"    {n!r}: {{'pkts': {a['pkts']}, 'errs': {a['errs']}, "
            f"'drops': {a['drops']}}},"
        )
    out.append("}\n")
    return "\n".join(out)


def gen(root: Path) -> int:
    target = root / _GEN_PATH
    target.write_text(_render(root), encoding="utf-8")
    print(f"datalogger_registry_gen: wrote {target}")
    return 0


def check(root: Path) -> int:
    target = root / _GEN_PATH
    want = _render(root)
    have = target.read_text(encoding="utf-8") if target.exists() else ""
    if want != have:
        print("❌ datalogger_registry drift: sw/stream/datalogger_registry.py is stale "
              "vs tools/datalogger-builder/config/datalogger_config.yml. Run "
              "`python3 tools/datalogger-builder/datalogger_registry_gen.py gen`.",
              file=sys.stderr)
        return 1
    print("✅ datalogger_registry in sync with datalogger_config.yml")
    return 0


def main(argv: list[str]) -> int:
    root = _repo_root(Path(__file__).parent)
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "gen":
        return gen(root)
    if cmd == "check":
        return check(root)
    print(f"usage: {argv[0]} [gen|check]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
