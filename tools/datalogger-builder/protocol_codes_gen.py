#!/usr/bin/env python3
# rr unknown-llm (AI-generated)
"""Single-source the SW decoders' per-protocol message-type + event codes from
the *_datalogger_protocol.yml contracts (DS-P3.59).

The protocol YAMLs are the contract; this makes them the SINGLE SOURCE OF TRUTH
for the decoder side too — mirroring id_gen.py, which already single-sources the
domain codes from system_ids.yml. It emits sw/stream/protocol_codes.py (the
generated TYPE_/EVENTS tables decoders.py imports) and a check() drift-gate that
the datalogger-builder pre_build hook + a pytest run, so a 0x09-typo can't desync
the YAML contract from the decoder.

Usage:
  protocol_codes_gen.py gen      # regenerate sw/stream/protocol_codes.py
  protocol_codes_gen.py check    # exit 1 if the generated file is stale (drift)
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

# Datalogger dir -> SW symbol prefix. qspi backs DOMAIN_SPI; uart's richer 8-byte
# payload decoder keeps its own struct but its event table is single-sourced too.
PROTOCOLS = {"uart": "UART", "i2c": "I2C", "qspi": "SPI", "jtag": "JTAG", "can": "CAN"}

_GEN_PATH = Path("sw/stream/protocol_codes.py")
_HEADER = (
    '"""GENERATED by tools/datalogger-builder/protocol_codes_gen.py (DS-P3.59) — '
    "DO NOT EDIT.\n\n"
    "Per-protocol message-type + event-code tables, single-sourced from the\n"
    "hw/rtl/datalogger/*/*_datalogger_protocol.yml contracts. Regenerate with\n"
    "`python3 tools/datalogger-builder/protocol_codes_gen.py gen`; the\n"
    "datalogger-builder pre_build hook + test_protocol_codes_drift.py gate it.\n"
    '"""\n'
)


def _repo_root(start: Path) -> Path:
    p = start.resolve()
    for cand in (p, *p.parents):
        if (cand / "hw" / "rtl" / "datalogger").is_dir():
            return cand
    raise SystemExit("protocol_codes_gen: can't find repo root (hw/rtl/datalogger)")


def _parse_int(v) -> int:
    return v if isinstance(v, int) else int(str(v).strip(), 0)


def _events(constants: dict) -> dict[int, str]:
    """code -> name. Events live under 'events:' or (UART) 'status_codes:'."""
    for key in ("events", "status_codes"):
        block = constants.get(key)
        if isinstance(block, dict):
            return {_parse_int(v): k for k, v in block.items()}
    return {}


def _types(constants: dict) -> dict[str, int]:
    """name -> type code. Either a 'message_types:' block or flat
    '<proto>_type_<name>' keys (i2c/qspi). Excludes '*_width' fields."""
    block = constants.get("message_types")
    if isinstance(block, dict):
        return {k: _parse_int(v) for k, v in block.items()}
    out: dict[str, int] = {}
    for k, v in constants.items():
        if "_type_" in k:                      # i2c_type_event, spi_type_payload_a
            out[k.split("_type_", 1)[1]] = _parse_int(v)
    return out


def _load(root: Path, proto: str) -> tuple[dict[str, int], dict[int, str]]:
    ymls = sorted((root / "hw" / "rtl" / "datalogger" / proto).glob("*protocol*.yml"))
    if not ymls:
        raise SystemExit(f"protocol_codes_gen: no protocol yml for {proto}")
    constants = yaml.safe_load(ymls[0].read_text(encoding="utf-8")).get("constants", {})
    return _types(constants), _events(constants)


def _render(root: Path) -> str:
    out = [_HEADER]
    for proto, pfx in PROTOCOLS.items():
        types, events = _load(root, proto)
        out.append(f"# {proto}_datalogger_protocol.yml")
        out.append(f"{pfx}_TYPES = {{")
        for name, code in types.items():
            out.append(f"    {name!r}: 0b{code:b},")
        out.append("}")
        out.append(f"{pfx}_EVENTS = {{")
        for code, name in sorted(events.items()):
            out.append(f"    0x{code:02X}: {name!r},")
        out.append("}\n")
    return "\n".join(out)


def gen(root: Path) -> int:
    target = root / _GEN_PATH
    target.write_text(_render(root), encoding="utf-8")
    print(f"protocol_codes_gen: wrote {target}")
    return 0


def check(root: Path) -> int:
    target = root / _GEN_PATH
    want = _render(root)
    have = target.read_text(encoding="utf-8") if target.exists() else ""
    if want != have:
        print("❌ protocol_codes drift: sw/stream/protocol_codes.py is stale vs "
              "the *_datalogger_protocol.yml contracts. Run "
              "`python3 tools/datalogger-builder/protocol_codes_gen.py gen`.",
              file=sys.stderr)
        return 1
    print("✅ protocol_codes in sync with the protocol YAML contracts")
    return 0


def main(argv: list[str]) -> int:
    root = _repo_root(Path(__file__).parent)
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "gen":
        return gen(root)
    if cmd == "check":
        return check(root)
    print(f"usage: {argv[0]} [gen|check]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
